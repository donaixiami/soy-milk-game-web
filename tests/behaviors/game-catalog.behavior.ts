import { describe, it } from 'vitest';

// Feature: 公开游戏目录与详情
//
// Scenario: 搜索已发布游戏
//   Given 平台存在已发布和未发布的游戏
//   When 访客打开游戏目录并按关键词搜索
//   Then 页面只展示匹配的已发布游戏
//   And 首屏 HTML 包含可索引的游戏标题、简介和详情链接
//
// Scenario: 从支持人数派生玩家标签
//   Given 游戏声明支持人数数组
//   When 目录和详情展示游戏能力
//   Then 支持人数包含 1 时展示单人标签
//   And 支持人数包含 2 时展示双人标签
//   And 支持人数包含 3 或 4 时展示多人标签
//
// Scenario: 纯单人游戏只允许开始单人会话
//   Given 游戏仅声明支持 1 人且没有同屏或在线能力
//   When 访客打开游戏详情
//   Then 页面展示单人游玩入口
//   And 页面不展示同屏入口或创建在线房间入口
//
// Scenario: 按能力展示同屏与在线入口
//   Given 游戏分别声明同屏人数和在线房间人数
//   When 访客打开游戏详情
//   Then 只有同屏人数非空时展示同屏游玩入口
//   And 只有在线房间人数非空时展示创建在线房间入口
//
// Scenario: 游戏详情输出 SEO 元信息
//   Given 游戏存在公开标题、摘要、封面和规范路径
//   When 服务端渲染游戏详情
//   Then 输出唯一 H1、description、canonical、Open Graph 和 VideoGame 结构化数据
//
// Scenario: 不存在或未发布的游戏返回 404
//   Given slug 不存在或游戏尚未发布
//   When 访客请求游戏详情
//   Then 服务端返回真实 404 且页面不可索引

describe('公开游戏目录与详情行为', () => {
  it('搜索已发布游戏');
  it('从支持人数派生玩家标签');
  it('纯单人游戏只允许开始单人会话');
  it('按能力展示同屏与在线入口');
  it('游戏详情输出 SEO 元信息');
  it('不存在或未发布的游戏返回 404');
});
